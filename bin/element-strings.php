<?php
/**
 * Writes src/Elements/strings.php: one __() call per translatable string of every element.json,
 * so `wp i18n make-pot` puts them in the POT file (it does not read element.json).
 *
 * Usage: php bin/element-strings.php [--check]   (--check: exit 1 when the file is out of date)
 *
 * @package Buddy_Builder
 */

// phpcs:disable WordPress.WP.AlternativeFunctions,WordPress.Security.EscapeOutput.OutputNotEscaped,WordPress.NamingConventions.PrefixAllGlobals,WordPress.PHP.DevelopmentFunctions -- CLI script, no WordPress.

define( 'ABSPATH', __DIR__ . '/' );
require dirname( __DIR__ ) . '/src/Kit/Schema.php';

$root    = dirname( __DIR__ );
$strings = array();

foreach ( glob( $root . '/src/Elements/*/element.json' ) as $file ) {
	$schema = Buddy_Builder\Kit\Schema::load( $file );
	if ( ! $schema ) {
		fwrite( STDERR, "Invalid element.json: $file\n" );
		exit( 1 );
	}
	foreach ( Buddy_Builder\Kit\Schema::strings( $schema ) as $text ) {
		// Numbers (column counts) need no translation; as array keys they would become integers.
		if ( is_numeric( $text ) ) {
			continue;
		}
		$strings[ $text ][] = $schema['name'];
	}
}

ksort( $strings );

$out  = "<?php\n";
$out .= "/**\n * Translatable strings of src/Elements/<name>/element.json, for translation tools only (never runs).\n";
$out .= " * Generated by bin/element-strings.php; do not edit, run php bin/element-strings.php.\n *\n * @package Buddy_Builder\n */\n\n";
$out .= "defined( 'ABSPATH' ) || exit;\n\nreturn;\n\n// phpcs:disable\n";
foreach ( $strings as $text => $elements ) {
	if ( false !== strpos( $text, '%' ) ) {
		$out .= '/* translators: placeholders as described in the element setting (' . implode( ', ', array_unique( $elements ) ) . ") */\n";
	}
	$out .= '__( ' . var_export( (string) $text, true ) . ", 'stax-buddy-builder' );\n";
}

$target = $root . '/src/Elements/strings.php';

if ( in_array( '--check', $argv, true ) ) {
	if ( ! is_readable( $target ) || file_get_contents( $target ) !== $out ) {
		fwrite( STDERR, "src/Elements/strings.php is out of date: run php bin/element-strings.php\n" );
		exit( 1 );
	}
	echo "src/Elements/strings.php is up to date.\n";
	exit( 0 );
}

file_put_contents( $target, $out );
echo count( $strings ) . " strings written to src/Elements/strings.php\n";
