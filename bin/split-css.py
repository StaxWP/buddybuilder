#!/usr/bin/env python3
"""Split the BuddyPress Nouveau fork (templates/buddypress/assets/buddypress.css) into one file per template type.

Each output keeps the sections a page type needs, in the original order (no cascade change), so a page loads one
smaller file instead of the whole fork. Sections are found by their "@section" / "@subsection" titles.
Pages without a known type keep the full file.

Usage: [BPB_LIGHTNINGCSS=/path/to/lightningcss] bin/split-css.py
"""
import os
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "templates/buddypress/assets/buddypress.css"
OUT = ROOT / "templates/buddypress/assets/parts"

# Chunk id => title of the section that starts it (chunks run until the next listed title).
CHUNKS = [
    ("base_head", None),
    ("activity", "3.1 - Activity Loop"),
    ("blogs_loop", "3.2 - Blogs Loop"),
    ("groups_loop", "3.2 - Groups Loop"),
    ("members_loop", "3.2 - Members Loop"),
    ("directories", "4.0 - Directories"),
    ("group_create", "4.1 - Groups Creation Steps"),
    ("single", "5.0 - Single Item screens"),
    ("group_header", "5.1.1 - item-header Groups"),
    ("user_header", "5.1.2 - Item Header User Accounts"),
    ("body_global", "5.2 - Item Body: Global"),
    ("group_body", "5.2.1 - Item Body Groups"),
    ("user_body", "5.2.2 - Item Body User Accounts"),
    ("messages", "5.2.2.5 - Private Messaging"),
    ("settings", "5.2.2.6 - Settings"),
    ("base_tail", "6.0 - Forms"),
]

ALL = [c for c, _ in CHUNKS]
BASE = ["base_head", "base_tail"]
TYPES = {
    "members-directory": BASE + ["members_loop", "directories"],
    "groups-directory": BASE + ["groups_loop", "directories"],
    "sitewide-activity": BASE + ["activity", "directories"],
    "register-page": BASE + ["directories"],
    "group-profile": BASE + ["activity", "groups_loop", "members_loop", "single", "group_header", "body_global", "group_body"],
    "member-profile": [c for c in ALL if c not in ("group_create", "group_header", "group_body")],
}


def chunks(css):
    lines = css.split("\n")
    starts = [(0, "base_head")]
    for cid, title in CHUNKS[1:]:
        pattern = re.compile(r"^\s*\*\s*@(sub)?section\s+" + re.escape(title))
        found = [i for i, line in enumerate(lines) if pattern.search(line)]
        if not found:
            raise SystemExit("section not found: " + title)
        # The comment block opens two lines above the title ("/**" and the dashes line).
        start = found[0]
        while start > 0 and not lines[start].lstrip().startswith("/**"):
            start -= 1
        starts.append((start, cid))
    starts.sort()
    out = {}
    for n, (start, cid) in enumerate(starts):
        end = starts[n + 1][0] if n + 1 < len(starts) else len(lines)
        out[cid] = "\n".join(lines[start:end])
    return out


def main():
    css = SOURCE.read_text()
    parts = chunks(css)
    OUT.mkdir(exist_ok=True)
    tool = os.environ.get("BPB_LIGHTNINGCSS")
    for type_, wanted in TYPES.items():
        body = "\n".join(parts[c] for c, _ in CHUNKS if c in wanted)
        src = OUT / (type_ + ".css")
        src.write_text("/* BuddyPress Nouveau (BuddyBuilder fork), sections for " + type_ + ". Generated by bin/split-css.py, do not edit. */\n" + body + "\n")
        target = OUT / (type_ + ".min.css")
        if tool:
            subprocess.run([tool, "--minify", "--targets", "defaults", str(src), "-o", str(target)], check=True)
        else:
            target.write_text(re.sub(r"\s+", " ", re.sub(r"/\*.*?\*/", "", body, flags=re.S)))
        print(type_, src.stat().st_size, target.stat().st_size)


if __name__ == "__main__":
    main()
