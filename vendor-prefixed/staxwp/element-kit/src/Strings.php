<?php
/**
 * Translation strings file of a plugin's elements (element kit).
 *
 * KIT RULES: PHP 7.4 syntax, no WordPress (runs from a CLI script), no plugin-specific names.
 *
 * @package StaxWP\ElementKit
 */

namespace Buddy_Builder\Vendor\ElementKit;

defined( 'ABSPATH' ) || exit;

/**
 * Writes <root>/src/Elements/strings.php: one __() call per translatable string of every element.json, so
 * `wp i18n make-pot` puts them in the POT file (it does not read element.json). A plugin calls run() from a small
 * CLI script (bin/element-strings.php) that defines ABSPATH and loads this class from its prefixed copy.
 */
final class Strings {

	/**
	 * Elements folder, relative to the plugin root.
	 */
	const DIR = 'src/Elements';

	/**
	 * Strings of every element.json under a plugin root.
	 *
	 * @param string $root Plugin root.
	 * @return array|null Text => element names, sorted by text; null when an element.json is invalid.
	 */
	public static function collect( $root ) {
		$strings = array();

		foreach ( (array) glob( rtrim( $root, '/' ) . '/' . self::DIR . '/*/element.json' ) as $file ) {
			$schema = Schema::load( $file );
			if ( ! $schema ) {
				return null;
			}
			foreach ( Schema::strings( $schema ) as $text ) {
				$strings[ (string) $text ][] = $schema['name'];
			}
		}

		ksort( $strings );

		return $strings;
	}

	/**
	 * Contents of the strings file.
	 *
	 * @param array  $strings   Text => element names (collect()).
	 * @param string $domain    Text domain.
	 * @param string $package   Docblock package.
	 * @param string $generator Script named in the header, e.g. "bin/element-strings.php".
	 * @param string $command   Command named in the header to regenerate the file.
	 * @return string
	 */
	public static function file( array $strings, $domain, $package, $generator, $command ) {
		$out  = "<?php\n";
		$out .= "/**\n * Translatable strings of src/Elements/<name>/element.json, for translation tools only (never runs).\n";
		$out .= ' * Generated by ' . $generator . '; do not edit, run ' . $command . ".\n *\n * @package " . $package . "\n */\n\n";
		$out .= "defined( 'ABSPATH' ) || exit;\n\nreturn;\n\n// phpcs:disable\n";

		foreach ( $strings as $text => $elements ) {
			$text = (string) $text;
			if ( false !== strpos( $text, '%' ) ) {
				$out .= '/* translators: placeholders as described in the element setting (' . implode( ', ', array_unique( $elements ) ) . ") */\n";
			}
			$out .= '__( ' . var_export( $text, true ) . ', ' . var_export( (string) $domain, true ) . " );\n"; // phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_var_export -- PHP source output.
		}

		return $out;
	}

	/**
	 * Write the strings file, or check that it is up to date.
	 *
	 * @param array $args Keys root, domain, package, generator, command (see file()); check: compare only.
	 * @return int Exit code: 0 written or up to date, 1 invalid element.json or out of date.
	 */
	public static function run( array $args ) {
		$strings = self::collect( $args['root'] );
		$target  = rtrim( $args['root'], '/' ) . '/' . self::DIR . '/strings.php';
		$name    = self::DIR . '/strings.php';

		if ( null === $strings ) {
			fwrite( STDERR, "Invalid element.json under {$args['root']}\n" ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_fwrite -- CLI.
			return 1;
		}

		$out = self::file( $strings, $args['domain'], $args['package'], $args['generator'], $args['command'] );

		if ( ! empty( $args['check'] ) ) {
			if ( ! is_readable( $target ) || file_get_contents( $target ) !== $out ) { // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- local file.
				fwrite( STDERR, "$name is out of date: run {$args['command']}\n" ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_fwrite -- CLI.
				return 1;
			}
			echo "$name is up to date.\n"; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- CLI.
			return 0;
		}

		file_put_contents( $target, $out ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents -- CLI.
		echo count( $strings ) . " strings written to $name\n"; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- CLI.

		return 0;
	}
}
